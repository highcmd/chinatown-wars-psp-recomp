static const u8 *glyph(char c) {
	if (c >= 'a' && c <= 'z' && c != 'x') c = (char)(c - 'a' + 'A');
	for (auto &g : FONT)
		if (g.c == c) return g.rows;
	return nullptr;   // space and anything unknown
}

void osd_message(const char *fmt, ...) {
	char buf[96];
	va_list ap;
	va_start(ap, fmt);
	vsnprintf(buf, sizeof(buf), fmt, ap);
	va_end(ap);
	std::lock_guard<std::mutex> lk(s_mtx);
	s_msg = buf;
	s_msg_until = rt_time_us() + 2000000;
}

void osd_on_vblank() {
	extern u64 g_frames_finished;
	static u64 lastT, lastF;
	u64 now = rt_time_us();
	if (now - lastT < 500000) return;
	if (lastT) {
		char buf[32];
		snprintf(buf, sizeof(buf), "%.0f FPS", (g_frames_finished - lastF) * 1e6 / (now - lastT));
		std::lock_guard<std::mutex> lk(s_mtx);
		s_fps_text = buf;
	}
	lastT = now;
	lastF = g_frames_finished;
}

bool osd_build(std::vector<u32> &px, int &w, int &h) {
	std::string lines[2];
	int n = 0;
	{
		std::lock_guard<std::mutex> lk(s_mtx);
		if (g_osd_fps && !s_fps_text.empty()) lines[n++] = s_fps_text;
		if (!s_msg.empty() && rt_time_us() < s_msg_until) lines[n++] = s_msg;
	}
	if (!n) return false;
	size_t cols = 0;
	for (int i = 0; i < n; i++) cols = std::max(cols, lines[i].size());
	w = (int)cols * 6 + 3;   // 1 px gap between glyphs, 2 px border
	h = n * 9 + 2;
	px.assign((size_t)w * h, 0xFF000000u);   // opaque black box (RGBA in memory: R G B A)
	for (int i = 0; i < n; i++)
		for (size_t k = 0; k < lines[i].size(); k++) {
			const u8 *g = glyph(lines[i][k]);
			if (!g) continue;
			for (int y = 0; y < 7; y++)
				for (int x = 0; x < 5; x++)
					if (g[y] & (0x10 >> x)) px[(size_t)(2 + i * 9 + y) * w + 2 + k * 6 + x] = 0xFFFFFFFFu;
		}
	return true;
}

void osd_blit(u32 *dst, int dw, int dh, int scale) {
	std::vector<u32> px;
	int w, h;
	if (!osd_build(px, w, h)) return;
	for (int y = 0; y < h * scale && y < dh; y++)
		for (int x = 0; x < w * scale && x < dw; x++)
			dst[(size_t)y * dw + x] = px[(size_t)(y / scale) * w + x / scale];
}
